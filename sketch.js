function draw(){
  background(92,148,252);
  collisionCheckerGround();

  mover();
  if (kb.presses('space')) {
    world.gravity = 9;
    mario.y -= 16;

  }  
  if (mouse.presses()){
    mario.y = mouse.y;
    mario.x = mouse.x;

  }

  camera.x = mario.x;
  camera.y = height/2;
}

function collisionCheckerGround(){
  if (mario.collide(ground)){
    mario.y = Math.round(mario.y);

  }
  if (mario.collide(brick)){
    mario.y = Math.round(mario.y);
    mario.x = Math.round(mario.x);

  }  
  if (mario.collide(questionB)){
    mario.y = Math.round(mario.y);
    mario.x = Math.round(mario.x);

  }
  // if (mario.collide())

}
